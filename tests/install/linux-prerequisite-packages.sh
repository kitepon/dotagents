#!/usr/bin/env bash
# root処理のpackage選択をstubで実行し、実機のapt・設定には触らない。
# shellcheck disable=SC2329,SC2034 # sourceする製品処理がfixtureの関数とOS値を消費する。
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
fixture="$(mktemp -d)"
trap 'rm -rf "$fixture"' EXIT
awk '/^packages=\(/ { capture=1 } /^systemctl enable --now cron/ { capture=0 } capture' \
  "$ROOT/bin/setup-linux-prerequisites-root.sh" >"$fixture/packages.sh"
[ -s "$fixture/packages.sh" ] || { echo 'FAIL: package処理が見つかりません' >&2; exit 1; }

for docker_package in docker-ce docker.io absent; do
  (
    calls="$fixture/$docker_package.calls"
    export calls
    dpkg-query() {
      local package="${*: -1}"
      case "$package" in
        shellcheck) return 1 ;;
        docker-ce|docker.io) [ "$package" = "$docker_package" ] || return 1 ;;
      esac
      printf 'ii '
    }
    apt-get() { printf '%s\n' "$*" >>"$calls"; }
    env() { shift; "$@"; }
    install() { :; }
    curl() { :; }
    chmod() { :; }
    tee() { cat >"$fixture/docker.sources"; }
    dpkg() { printf 'amd64\n'; }
    VERSION_CODENAME=noble
    VERSION_ID=24.04
    setup_variant=server
    # shellcheck disable=SC1091 # 検査対象から取り出した実処理。
    source "$fixture/packages.sh"
    printf 'update\ninstall -y shellcheck\n' >"$fixture/expected"
    if [ "$docker_package" = absent ]; then
      printf 'update\ninstall --no-remove -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin\n' >>"$fixture/expected"
      grep -Fxq 'URIs: https://download.docker.com/linux/ubuntu' "$fixture/docker.sources"
      grep -Fxq 'Suites: noble' "$fixture/docker.sources"
    fi
    diff -u "$fixture/expected" "$calls"
  )
done

# Rabbit (linux variant) also gets the GUI test / packaging packages, named by Ubuntu release; server never does.
for case_name in linux-24.04 linux-22.04 server-24.04; do
  (
    variant="${case_name%-*}"; release="${case_name#*-}"
    calls="$fixture/$case_name.calls"
    dpkg-query() { local package="${*: -1}"; case "$package" in docker-ce) printf 'ii ' ;; *) return 1 ;; esac; }
    apt-get() { printf '%s\n' "$*" >>"$calls"; }
    env() { shift; "$@"; }
    VERSION_ID="$release"
    setup_variant="$variant"
    # shellcheck disable=SC1091 # 検査対象から取り出した実処理。
    source "$fixture/packages.sh"
    installed="$(grep '^install' "$calls")"
    for wanted in xvfb xauth xdotool squashfs-tools desktop-file-utils apparmor; do
      if [ "$variant" = linux ]; then [[ " $installed " == *" $wanted "* ]] || { echo "FAIL: $case_name に $wanted が無い" >&2; exit 1; }
      else [[ " $installed " != *" $wanted "* ]] || { echo "FAIL: server に GUI package $wanted" >&2; exit 1; }; fi
    done
    case "$case_name" in
      linux-24.04) [[ " $installed " == *" libfuse2t64 "* && " $installed " != *" libfuse2 "* ]] || { echo 'FAIL: 24.04はlibfuse2t64' >&2; exit 1; } ;;
      linux-22.04) [[ " $installed " == *" libfuse2 "* && " $installed " != *" libfuse2t64 "* ]] || { echo 'FAIL: 22.04はlibfuse2' >&2; exit 1; } ;;
      server-24.04) [[ " $installed " != *" libfuse2"* ]] || { echo 'FAIL: serverにlibfuse2' >&2; exit 1; } ;;
    esac
  )
done
echo 'linux-prerequisite-packages: OK（既存Docker保持・不足package限定・Rabbitだけ GUI試験package）'
